#!/usr/bin/env python3
"""
===================================================================================
LAUNCH FILE ДЛЯ ОДОМЕТРИИ
===================================================================================

ЧТО ТАКОЕ LAUNCH FILE?
----------------------
Launch файл - это "сценарий запуска" для ROS2 нод.
Вместо того чтобы запускать каждую ноду вручную командой:
    ros2 run verter_admin odometry_node

Мы можем запустить все нужные ноды одной командой:
    ros2 launch verter_admin odometry.launch.py

Аналогия из Java:
- Как docker-compose.yml для запуска нескольких сервисов
- Или как конфигурация запуска в IntelliJ IDEA


ЗАЧЕМ ЭТО НУЖНО?
-----------------
1. Удобство: запуск одной командой вместо десятков
2. Конфигурация: можно передавать параметры нодам
3. Зависимости: можно указать порядок запуска
4. Воспроизводимость: одинаковый запуск на разных машинах


ЧТО ЗАПУСКАЕТ ЭТОТ LAUNCH FILE?
--------------------------------
1. odometry_node - нода одометрии (наша только что созданная)

В будущем здесь можно добавить:
2. robot_state_publisher - публикует URDF модель робота
3. joint_state_publisher - публикует состояние суставов (если есть)
4. static_transform_publisher - статические трансформации (base_link -> sensors)

===================================================================================
"""

from launch import LaunchDescription
from launch_ros.actions import Node


def generate_launch_description():
    """
    Функция генерации описания запуска.

    Эта функция ОБЯЗАТЕЛЬНО должна называться именно так!
    ROS2 ищет эту функцию при запуске launch файла.

    Returns:
        LaunchDescription: Описание что и как запускать
    """

    # ============================================================================
    # НОДА ОДОМЕТРИИ
    # ============================================================================
    # Создаем описание ноды одометрии
    odometry_node = Node(
        # Пакет в котором находится нода
        package='verter_admin',

        # Исполняемый файл (название из entry_points в setup.py)
        executable='odometry_node',

        # Имя ноды в системе ROS2 (можно переопределить)
        # Если не указать, будет использовано имя из самой ноды
        name='odometry_node',

        # Куда выводить логи:
        # 'screen' - в терминал
        # 'log' - в файл
        # 'both' - и туда и туда
        output='both',

        # Параметры ноды (опционально)
        # Можно передать параметры конфигурации
        # Например:
        # parameters=[{
        #     'max_linear_velocity': 0.5,
        #     'max_angular_velocity': 1.0,
        #     'update_frequency': 50.0
        # }]

        # Переназначение топиков (опционально)
        # Если нужно изменить имена топиков
        # remappings=[
        #     ('/cmd_vel', '/my_robot/cmd_vel'),
        #     ('/odom', '/my_robot/odom')
        # ]
    )

    # ============================================================================
    # ВОЗВРАТ ОПИСАНИЯ ЗАПУСКА
    # ============================================================================
    # LaunchDescription принимает список нод и действий для запуска
    return LaunchDescription([
        # Запускаем ноду одометрии
        odometry_node,

        # В будущем здесь добавятся другие ноды:
        # robot_state_publisher_node,
        # static_transforms,
        # и т.д.
    ])
